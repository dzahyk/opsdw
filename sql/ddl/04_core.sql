-- Core: conformed star schema.
CREATE TABLE IF NOT EXISTS core.dim_date (
    date_key     integer PRIMARY KEY,           -- yyyymmdd
    date         date    NOT NULL UNIQUE,
    year         smallint NOT NULL,
    quarter      smallint NOT NULL,
    month        smallint NOT NULL,
    month_start  date    NOT NULL,
    year_month   text    NOT NULL,              -- 'YYYY-MM'
    iso_week     smallint NOT NULL,
    day_of_week  smallint NOT NULL,             -- ISO: 1 = Monday
    day_name     text    NOT NULL,
    is_weekend   boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS core.dim_city (
    city_key   smallint PRIMARY KEY,
    city_code  text NOT NULL UNIQUE,
    city_name  text NOT NULL,
    province   text NOT NULL,
    island     text NOT NULL
);

CREATE TABLE IF NOT EXISTS core.ref_commission_tier (
    commission_tier text PRIMARY KEY,
    commission_rate numeric(5,4) NOT NULL CHECK (commission_rate BETWEEN 0 AND 1)
);

-- SCD1: customer attributes are overwritten (corrections, not history we analyse).
CREATE TABLE IF NOT EXISTS core.dim_customer (
    customer_key        bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    customer_id         text NOT NULL UNIQUE,
    signup_at           timestamptz,
    signup_date_key     integer,
    city_code           text,
    acquisition_channel text,
    source_updated_at   timestamptz,
    is_inferred         boolean NOT NULL DEFAULT false
);

-- SCD1 for couriers.
CREATE TABLE IF NOT EXISTS core.dim_courier (
    courier_key       bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    courier_id        text NOT NULL UNIQUE,
    city_code         text,
    vehicle_type      text,
    joined_at         timestamptz,
    source_updated_at timestamptz
);

-- SCD2: commission tier changes must be attributed to the tier valid when the
-- order was placed, otherwise historical commission revenue is restated.
CREATE TABLE IF NOT EXISTS core.dim_merchant (
    merchant_key    bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    merchant_id     text        NOT NULL,
    version_no      integer     NOT NULL,
    merchant_name   text,
    category        text,
    city_code       text,
    commission_tier text,
    commission_rate numeric(5,4),
    valid_from      timestamptz NOT NULL,       -- inclusive; first version is -infinity
    valid_to        timestamptz NOT NULL,       -- exclusive; current version is infinity
    is_current      boolean     NOT NULL,
    UNIQUE (merchant_id, version_no),
    EXCLUDE USING gist (merchant_id WITH =, tstzrange(valid_from, valid_to, '[)') WITH &&)
);

-- Transaction fact: one row per order lifecycle event. Append-only and queried
-- by time window -> range-partitioned by month (partitions created by the pipeline).
CREATE TABLE IF NOT EXISTS core.fact_order_events (
    event_id       text        NOT NULL,
    event_at       timestamptz NOT NULL,
    event_date_key integer     NOT NULL,
    order_id       text        NOT NULL,
    event_type     text        NOT NULL,
    courier_key    bigint,
    cancel_reason  text,
    rating         smallint,
    PRIMARY KEY (event_id, event_at)
) PARTITION BY RANGE (event_at);
CREATE TABLE IF NOT EXISTS core.fact_order_events_default PARTITION OF core.fact_order_events DEFAULT;

-- Accumulating snapshot fact: one row per order, milestones filled in as events arrive.
CREATE TABLE IF NOT EXISTS core.fact_orders (
    order_id            text PRIMARY KEY,
    customer_key        bigint   NOT NULL,
    merchant_key        bigint   NOT NULL,
    courier_key         bigint   NOT NULL,      -- -1 = not (yet) assigned
    city_key            smallint NOT NULL,
    created_date_key    integer  NOT NULL,
    customer_id         text     NOT NULL,      -- natural keys kept for re-keying late dimensions
    merchant_id         text     NOT NULL,
    created_at          timestamptz NOT NULL,
    assigned_at         timestamptz,
    picked_up_at        timestamptz,
    delivered_at        timestamptz,
    cancelled_at        timestamptz,
    order_status        text NOT NULL CHECK (order_status IN ('created','assigned','picked_up','delivered','cancelled')),
    cancel_stage        text CHECK (cancel_stage IN ('before_assignment','after_assignment','after_pickup')),
    cancel_reason       text,
    is_delivered        boolean NOT NULL,
    is_cancelled        boolean NOT NULL,
    items_amount        numeric(14,2) NOT NULL,
    delivery_fee        numeric(14,2) NOT NULL,
    discount_amount     numeric(14,2) NOT NULL,
    gmv                 numeric(14,2) NOT NULL,  -- items + fee - discount, delivered orders only, else 0
    commission_rate     numeric(5,4),
    commission_amount   numeric(14,2) NOT NULL,  -- items_amount * rate valid at created_at, delivered only
    payment_method      text NOT NULL,
    distance_km         numeric(6,2)  NOT NULL,
    promised_minutes    integer       NOT NULL,
    assign_latency_min  numeric(10,2),
    delivery_minutes    numeric(10,2),
    is_on_time          boolean,                 -- null unless delivered
    assignment_count    integer NOT NULL,
    rating              smallint,
    source_updated_at   timestamptz NOT NULL,
    last_run_id         bigint NOT NULL
);

-- Monthly partitions 2023-01 .. 2026-12 (data generated for 2024-2025; the
-- extra months absorb late/early timestamps). Anything outside lands in DEFAULT,
-- which a data-quality check asserts is empty.
DO $$
DECLARE m date;
BEGIN
    FOR m IN SELECT generate_series(date '2023-01-01', date '2026-12-01', interval '1 month')::date LOOP
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS core.fact_order_events_%s PARTITION OF core.fact_order_events
             FOR VALUES FROM (%L) TO (%L)',
            to_char(m, 'YYYYMM'), m::timestamptz, (m + interval '1 month')::timestamptz);
    END LOOP;
END $$;
