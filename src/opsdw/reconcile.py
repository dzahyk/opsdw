"""KPI reconciliation: every dashboard KPI value must equal its SQL definition.

For every KPI in kpis/kpis.yml and every (month, city) cell, including the
'ALL' city roll-up, three values are compared:
  A canonical  - sql/kpi/*.sql on the core star schema (definition of record)
  B semantic   - the DAX measure's SQL translation evaluated on the bi.* views
  C dashboard  - the number embedded in the BUILT dashboard/dist/index.html
Tolerance: counts exact; IDR to the cent (0.005); ratios and minutes 1e-9.
"""
from __future__ import annotations

import csv
from decimal import Decimal
from pathlib import Path

import psycopg

from . import dashboard, kpis as kpi_mod
from .config import ROOT

DEFAULT_REPORT_DIR = ROOT / "data" / "reports"   # committed copy in docs/ is produced with --report-dir docs
TOL = {"count": 0, "IDR": 0.005, "ratio": 1e-9, "minutes": 1e-9}

SEMANTIC_TEMPLATE = """
SELECT d.year_month, CASE WHEN grouping(c.city_code) = 1 THEN 'ALL' ELSE c.city_code END AS city_code, {expr} AS value
FROM bi.fact_orders f
JOIN bi.dim_date d ON d.date_key = f.created_date_key      -- relationship fact_orders[created_date_key] -> dim_date
JOIN bi.dim_city c ON c.city_key = f.city_key               -- relationship fact_orders[city_key] -> dim_city
GROUP BY GROUPING SETS ((d.year_month, c.city_code), (d.year_month))
"""


def _f(v):
    return None if v is None else float(v) if isinstance(v, Decimal) else v


def canonical(conn, k) -> dict:
    return {(ym, c): _f(v) for ym, c, v in conn.execute((ROOT / k["canonical_sql"]).read_text()).fetchall()}


def semantic(conn, k) -> dict:
    return {(ym, c): _f(v) for ym, c, v in conn.execute(SEMANTIC_TEMPLATE.format(expr=k["semantic_sql"])).fetchall()}


def from_dashboard(ds: dict, key: str) -> dict:
    out = {}
    for city, series in ds["values"].items():
        for ym, v in zip(ds["months"], series[key]):
            out[(ym, city)] = v
    return out


def _close(a, b, tol) -> bool:
    if a is None or b is None:
        return a is None and b is None
    return abs(a - b) <= tol


def reconcile(conn: psycopg.Connection, build: bool = True, dist: Path = dashboard.DIST) -> list[dict]:
    if build:
        dashboard.render(dashboard.build_dataset(conn), dist)
    ds = dashboard.read_embedded(dist)
    rows = []
    for k in kpi_mod.kpis():
        a, b, c = canonical(conn, k), semantic(conn, k), from_dashboard(ds, k["key"])
        tol = TOL[k["unit"]]
        cells = sorted(set(a) | set(b) | set(c))
        for cell in cells:
            va, vb, vc = a.get(cell), b.get(cell), c.get(cell)
            # a city with no orders in a month is absent from SQL results; the dashboard holds None there
            ok = _close(va, vb, tol) and _close(va, vc, tol)
            rows.append({"kpi": k["id"], "key": k["key"], "unit": k["unit"], "year_month": cell[0], "city": cell[1],
                         "canonical_sql": va, "semantic_model": vb, "dashboard": vc, "status": "OK" if ok else "MISMATCH"})
    return rows


def write_reports(conn, rows: list[dict], out_dir: Path = DEFAULT_REPORT_DIR) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    OUT_MD, OUT_CSV = out_dir / "RECONCILIATION.md", out_dir / "reconciliation.csv"
    with OUT_CSV.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    db, n_orders, run = conn.execute(
        "SELECT current_database(), (SELECT count(*) FROM core.fact_orders), "
        "(SELECT max(run_id) FROM meta.etl_runs WHERE status = 'success')").fetchone()
    by_kpi: dict[str, list[dict]] = {}
    for r in rows:
        by_kpi.setdefault(r["kpi"], []).append(r)
    last = max(r["year_month"] for r in rows)
    lines = [
        "# KPI reconciliation sheet",
        "",
        "> Generated by `uv run opsdw reconcile`. Synthetic data only.",
        f"> Database `{db}` · {n_orders:,} orders in `core.fact_orders` · ETL run {run}.",
        "",
        "Each KPI is evaluated for every month x city cell (plus the `ALL` roll-up) along three independent paths:",
        "",
        "- **A canonical SQL** — `sql/kpi/*.sql` on the core star schema (definition of record)",
        "- **B semantic model** — SQL translation of the DAX measure, run on the Power BI views (`bi.*`)",
        "- **C dashboard** — the value embedded in the built `dashboard/dist/index.html` (additive KPIs from",
        "  `mart.city_daily`, roll-ups and ratios recomputed in Python)",
        "",
        "Tolerance: counts exact, IDR to the cent, ratios and minutes 1e-9. The DAX itself is **not executed**",
        "(no Power BI engine on macOS); B proves the measure logic, not the DAX syntax.",
        "",
        "| KPI | Cells compared | Mismatches | Status |",
        "|---|---:|---:|---|",
    ]
    names = {k["id"]: k["name"] for k in kpi_mod.kpis()}
    for kid, rs in by_kpi.items():
        bad = sum(r["status"] != "OK" for r in rs)
        lines.append(f"| {kid} {names[kid]} | {len(rs)} | {bad} | {'PASS' if not bad else 'FAIL'} |")
    lines += ["", f"## Latest month ({last}), all cities", "",
              "| KPI | A canonical SQL | B semantic model | C dashboard | Status |", "|---|---:|---:|---:|---|"]
    for r in rows:
        if r["year_month"] == last and r["city"] == "ALL":
            fmt = (lambda v: "—" if v is None else f"{v:,.6f}" if r["unit"] in ("ratio", "minutes") else f"{v:,.2f}"
                   if r["unit"] == "IDR" else f"{v:,.0f}")
            lines.append(f"| {r['kpi']} {names[r['kpi']]} | {fmt(r['canonical_sql'])} | {fmt(r['semantic_model'])} | "
                         f"{fmt(r['dashboard'])} | {r['status']} |")
    lines += ["", "Full cell-level detail: [`docs/reconciliation.csv`](reconciliation.csv).", ""]
    OUT_MD.write_text("\n".join(lines))
    return OUT_MD, OUT_CSV


def main(conn: psycopg.Connection, out_dir: Path = DEFAULT_REPORT_DIR) -> int:
    rows = reconcile(conn)
    OUT_MD, OUT_CSV = write_reports(conn, rows, out_dir)
    bad = [r for r in rows if r["status"] != "OK"]
    print(f"{len(rows)} KPI cells compared across canonical SQL / semantic model / dashboard: {len(bad)} mismatches")
    for r in bad[:20]:
        print("MISMATCH", r)
    print(f"wrote {OUT_MD} and {OUT_CSV}")
    return 1 if bad else 0
