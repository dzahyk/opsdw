"""KPI dictionary loader and Markdown generator (docs/KPI_DICTIONARY.md)."""
from __future__ import annotations

import yaml

from .config import ROOT

KPI_FILE = ROOT / "kpis" / "kpis.yml"
DICT_MD = ROOT / "docs" / "KPI_DICTIONARY.md"
DAX_FILE = ROOT / "powerbi" / "measures.dax"


def load() -> dict:
    return yaml.safe_load(KPI_FILE.read_text())


def kpis() -> list[dict]:
    doc = load()
    return [{**doc["defaults"], **k} for k in doc["kpis"]]


def render_dictionary() -> str:
    doc = load()
    d = doc["defaults"]
    lines = [
        "# KPI dictionary",
        "",
        "> Generated from `kpis/kpis.yml` by `uv run opsdw docs`. Do not edit by hand.",
        "> All data is **synthetic** (see `docs/DATA_SOURCE.md`); values describe a fictional platform.",
        "",
        "Defaults for every KPI unless a row overrides them:",
        "",
        f"- **Grain:** {d['grain']}",
        f"- **Time window:** {d['time_window']}",
        f"- **Filters:** {d['filters']}",
        f"- **Owner:** {d['owner']}",
        "",
        "| ID | KPI | Business question | Numerator | Denominator | Unit | Additive |",
        "|---|---|---|---|---|---|---|",
    ]
    for k in kpis():
        lines.append(f"| {k['id']} | {k['name']} | {k['business_question']} | {k['numerator']} | "
                     f"{k['denominator'] or '—'} | {k['unit']} | {'yes' if k['additive'] else 'no'} |")
    lines += ["", "## Definitions, DAX and caveats", ""]
    for k in kpis():
        lines += [
            f"### {k['id']} {k['name']}",
            "",
            f"- **Business question:** {k['business_question']}",
            f"- **Numerator:** {k['numerator']}",
            f"- **Denominator:** {k['denominator'] or '— (not a ratio)'}",
            f"- **Grain / time window / filters:** per defaults above",
            f"- **Owner:** {k['owner']}",
            f"- **Canonical SQL:** [`{k['canonical_sql']}`](../{k['canonical_sql']})",
            f"- **DAX:** `{k['dax']}`",
            f"- **DAX-equivalent SQL (executed in reconciliation):** `{k['semantic_sql']}`",
            f"- **Caveats:** {k['caveats']}",
            "",
        ]
    return "\n".join(lines)


def check_dax_file() -> list[str]:
    """Every KPI's DAX must appear verbatim in powerbi/measures.dax (and vice versa)."""
    text = DAX_FILE.read_text()
    measures = [ln.strip() for ln in text.splitlines() if " = " in ln and not ln.strip().startswith("//")]
    expected = [k["dax"] for k in kpis()]
    problems = [f"missing in measures.dax: {e}" for e in expected if e not in measures]
    problems += [f"not in kpis.yml: {m}" for m in measures if m not in expected]
    return problems


def render_query_catalog() -> str:
    """docs/ANALYTICS_QUERIES.md from the header comment of every sql/analytics/q*.sql file."""
    lines = ["# Analytical query catalog", "",
             "> Generated by `uv run opsdw docs` from the header comment of each file in `sql/analytics/`.",
             "> Every query has an expected-result test on the hand-built fixture",
             "> (`tests/test_analytics_queries.py`, data in `tests/fixtures/analytics_fixture.py`).", "",
             "| # | Query | Business question | Notes / techniques |", "|---|---|---|---|"]
    for path in sorted((ROOT / "sql" / "analytics").glob("q*.sql")):
        head = []
        for ln in path.read_text().splitlines():
            if not ln.startswith("--"):
                break
            head.append(ln[2:].strip())
        title = head[0]
        num, name = title.split(" ", 1)
        text = " ".join(head[1:])
        bq, _, notes = text.partition("?")
        bq = bq.replace("Business question:", "").strip() + "?"
        lines.append(f"| {num} | [{name}](../sql/analytics/{path.name}) | {bq} | {notes.strip()} |")
    return "\n".join(lines)


def write_dictionary() -> int:
    DICT_MD.write_text(render_dictionary() + "\n")
    print(f"wrote {DICT_MD.relative_to(ROOT)}")
    qc = ROOT / "docs" / "ANALYTICS_QUERIES.md"
    qc.write_text(render_query_catalog() + "\n")
    print(f"wrote {qc.relative_to(ROOT)}")
    problems = check_dax_file()
    for p in problems:
        print("DAX MISMATCH:", p)
    return 1 if problems else 0
